const validLanguage = (value) => ["ru", "en"].includes(value);
function storedPreference(key) {
  try { return localStorage.getItem(key); } catch { return null; }
}
function storePreference(key, value) {
  try { localStorage.setItem(key, value); } catch { /* Preferences still work for this visit. */ }
}
const linkLanguage = new URLSearchParams(location.search).get("lang");
let language = validLanguage(linkLanguage) ? linkLanguage : storedPreference("krug-language");
if (!validLanguage(language)) {
  const preferred = (navigator.languages || [navigator.language]).find((value) => /^(ru|en)\b/i.test(value));
  language = /^ru\b/i.test(preferred || "") ? "ru" : "en";
}
let theme = storedPreference("krug-theme");
if (!["system", "light", "dark"].includes(theme)) theme = "dark";
const darkMedia = matchMedia("(prefers-color-scheme: dark)");
const translationPattern = new RegExp(Object.keys(english).sort((a, b) => b.length - a.length)
  .map((key) => key.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")).join("|"), "g");
function t(copy) {
  return language === "ru" ? copy : copy.replace(translationPattern, (key) => english[key]);
}
function html(strings, ...values) {
  return strings.reduce((copy, part, index) => copy + t(part) + (index < values.length ? values[index] : ""), "");
}
